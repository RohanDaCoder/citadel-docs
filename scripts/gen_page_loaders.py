#!/usr/bin/env python3
"""Generate the page-loader registry TypeScript file."""
import os

PAGES_DIR = "/home/z/my-project/src/data/pages"
OUT = "/home/z/my-project/src/data/page-loaders.generated.ts"

entries = []
for fname in sorted(os.listdir(PAGES_DIR)):
    if not fname.endswith(".json"):
        continue
    page_id = fname[:-5]  # strip .json
    entries.append(f'  "{page_id}": () => import("./pages/{fname}"),')

with open(OUT, "w") as f:
    f.write("// AUTO-GENERATED by scripts/gen_page_loaders.py — do not edit\n")
    f.write("export type PageData = Record<string, unknown>;\n\n")
    f.write(f"export const pageLoaders: Record<string, () => Promise<{{ default: PageData }}>> = {{\n")
    f.write("\n".join(entries))
    f.write("\n};\n")

print(f"Generated {OUT} with {len(entries)} loaders")
